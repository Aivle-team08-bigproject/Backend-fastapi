-- =====================================================================
-- 9. 미결 — 보존기간 정책
-- =====================================================================
-- input_payload/output_payload/artifact에는 실제 데이터가 쌓인다.
-- 무기한 보관할 이유가 없으므로 정리 주기를 정해야 한다(팀 협의 필요).
--   후보) 완료된 job은 N일 후 payload만 NULL 처리하고 상태·시각은 남긴다
--        (통계·감사는 유지하면서 데이터만 줄이는 방식)
-- 캐시(stage_artifact_caches)는 재실행 편의용이므로 더 짧게 잡아도 무방하다.
